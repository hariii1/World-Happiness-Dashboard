import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Load and prepare data
df = pd.read_csv('/content/drive/MyDrive/dataset/world-happiness-report (1).csv')
df.columns = df.columns.str.lower().str.replace(' ', '_')
df_latest = df.loc[df.groupby('country_name')['year'].idxmax()]

sns.set_style("whitegrid")
plt.figure(figsize=(15, 10))


# 1. Top/Bottom 10 Countries
plt.subplot(2, 2, 1)
top_bottom = pd.concat([
    df_latest.nlargest(10, 'life_ladder'),
    df_latest.nsmallest(10, 'life_ladder')
])
sns.barplot(data=top_bottom, y='country_name', x='life_ladder',
            hue=top_bottom.index <= 9, palette={True: 'green', False: 'red'},
            dodge=False)
plt.title('Top 10 (Green) vs Bottom 10 (Red) Countries')
plt.xlabel('Happiness Score')
plt.ylabel('')
plt.axvline(x=df_latest['life_ladder'].median(), color='gray', linestyle='--')

# 2. Happiness Distribution
plt.subplot(2, 2, 2)
sns.histplot(df_latest['life_ladder'], bins=20, kde=True, color='purple')
plt.title('Global Happiness Distribution')
plt.xlabel('Happiness Score')
plt.ylabel('Number of Countries')

# 3. Correlation Heatmap
plt.subplot(2, 2, 3)
corr_matrix = df_latest[['life_ladder', 'log_gdp_per_capita', 'social_support',
                        'healthy_life_expectancy_at_birth', 'freedom_to_make_life_choices']].corr()
sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', center=0)
plt.title('Factor Correlations with Happiness')

# 4. GDP vs Happiness
plt.subplot(2, 2, 4)
sns.regplot(data=df_latest, x='log_gdp_per_capita', y='life_ladder',
            scatter_kws={'alpha':0.5}, line_kws={'color':'red'})
plt.title('GDP per Capita vs Happiness')
plt.xlabel('Log GDP per Capita')
plt.ylabel('Happiness Score')

plt.tight_layout()
plt.suptitle('World Happiness Dashboard', y=1.02, fontsize=16)
plt.show()