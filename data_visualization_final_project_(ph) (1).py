plt.title("Clustering of Countries Based on Happiness Factors")
plt.legend(title="Cluster")
plt.show()

fig = px.scatter_3d(df, x='log_gdp_per_capita', y='social_support', z='healthy_life_expectancy_at_birth',
                     color='Cluster', hover_data=['country_name'], title="3D Clustering of Countries")
fig.show()

